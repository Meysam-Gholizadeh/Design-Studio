import { useId, useRef, useState, type DragEvent } from 'react';
import { FileCode2, Upload } from 'lucide-react';
import { Button } from '@/components/common/Button';
import styles from './HtmlDropZone.module.css';

interface HtmlDropZoneProps {
  onFile: (file: File) => void;
  disabled?: boolean;
}

/** Choose or drop an .html file. Works with keyboard (button) and drag and drop. */
export function HtmlDropZone({ onFile, disabled }: HtmlDropZoneProps) {
  const inputRef = useRef<HTMLInputElement>(null);
  const [over, setOver] = useState(false);
  const hintId = useId();

  const onDrop = (e: DragEvent) => {
    e.preventDefault();
    setOver(false);
    const file = e.dataTransfer.files[0];
    if (file && !disabled) onFile(file);
  };

  return (
    <div
      className={styles.zone}
      data-over={over || undefined}
      onDragOver={(e) => {
        e.preventDefault();
        if (!disabled) setOver(true);
      }}
      onDragLeave={() => setOver(false)}
      onDrop={onDrop}
      data-testid="html-drop-zone"
    >
      <span className={styles.icon}>
        <FileCode2 size={26} aria-hidden="true" />
      </span>
      <p className={styles.title}>Drop an HTML dashboard here</p>
      <p className={styles.text} id={hintId}>
        One .html file up to 5 MB — for example a dashboard generated by an AI assistant.
      </p>
      <Button variant="primary" icon={<Upload size={16} aria-hidden="true" />} onClick={() => inputRef.current?.click()} disabled={disabled} aria-describedby={hintId}>
        Choose HTML file
      </Button>
      <input
        ref={inputRef}
        type="file"
        accept=".html,.htm,text/html"
        className={styles.input}
        aria-label="HTML dashboard file"
        tabIndex={-1}
        onChange={(e) => {
          const file = e.target.files?.[0];
          e.target.value = '';
          if (file) onFile(file);
        }}
      />
    </div>
  );
}
