/**
 * Generates a Power BI Project (PBIP) from a design: a report in the enhanced
 * report format (PBIR) plus a TMDL semantic model holding the fictional sample
 * data, ready to open in Power BI Desktop.
 *
 * Layout:
 *   <Name>/
 *     <Name>.pbip
 *     <Name>.Report/definition.pbir, definition/…, StaticResources/…
 *     <Name>.SemanticModel/definition.pbism, definition/…
 *     README.md, <slug>.powerbi-handoff.json, .gitignore
 */
import type { DashboardDocument } from '@/domain/schemas/document';
import { buildHandoffSpec, type HandoffSpec } from '../handoffSpec';
import { resolveTheme } from '../../themeService';
import { lit, objectEntry } from './literals';
import { pbirObjectName, projectFolderName } from './names';
import { buildSemanticModel, type SemanticModel } from './semanticModel';
import { semanticModelFiles } from './tmdl';
import { exportRoute, HTML_CONTENT_VISUAL } from './fidelity';
import { buildCardBackgroundContainer, buildVisualContainer, CARD_GLOW_MARGIN } from './visualContainer';

const SCHEMA = 'https://developer.microsoft.com/json-schemas/fabric';
export const PBIR_SCHEMAS = {
  pbip: `${SCHEMA}/pbip/pbipProperties/1.0.0/schema.json`,
  definitionPbir: `${SCHEMA}/item/report/definitionProperties/2.0.0/schema.json`,
  version: `${SCHEMA}/item/report/definition/versionMetadata/1.0.0/schema.json`,
  report: `${SCHEMA}/item/report/definition/report/2.1.0/schema.json`,
  pages: `${SCHEMA}/item/report/definition/pagesMetadata/1.0.0/schema.json`,
  page: `${SCHEMA}/item/report/definition/page/2.0.0/schema.json`,
} as const;

/** Power BI Desktop release whose report format these files target (June 2025). */
export const MIN_DESKTOP_VERSION = 'June 2025';
/** Report version stamped on the custom theme (Power BI Desktop, mid-2025). */
const THEME_REPORT_VERSION = '5.67';

export type ProjectFiles = Record<string, string | Uint8Array>;

export interface PbipProject {
  /** Top-level folder name inside the zip. */
  folder: string;
  /** Paths relative to the top-level folder. */
  files: ProjectFiles;
  model: SemanticModel;
  spec: HandoffSpec;
}

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

function decodeDataUrl(dataUrl: string): { bytes: Uint8Array; ext: string } {
  const [, meta = '', b64 = ''] = /^data:([^;]+);base64,(.*)$/.exec(dataUrl) ?? [];
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  const ext = meta === 'image/jpeg' ? 'jpg' : meta === 'image/webp' ? 'webp' : 'png';
  return { bytes, ext };
}

function htmlSection(spec: HandoffSpec, model: SemanticModel): string {
  if (model.htmlMeasures.size === 0) return '';
  const listed = spec.pages
    .flatMap((p) => p.visuals)
    .filter((v) => model.htmlMeasures.has(v.id))
    .map((v) => `| ${(v.title ?? v.designTypeLabel).replace(/\|/g, '/')} | ${v.powerBiVisual.rendering?.kind === 'html-content' ? v.powerBiVisual.rendering.features.join(', ') : ''} |`)
    .join('\n');
  return `
## Visuals drawn with HTML Content Secure

Some design visuals have no built-in Power BI equivalent: stat cards with trend lines and icons, ring gauges, tables with icons, photos or pills, and hero text. To keep them looking exactly as designed, they use the certified AppSource visual **[${HTML_CONTENT_VISUAL.displayName}](${HTML_CONTENT_VISUAL.appSourceUrl})**. It is listed in \`report.json\`, and Power BI Desktop loads it from AppSource when the report opens (an internet connection is needed the first time).

- Each one renders a measure in the display folder **"Design visuals (HTML)"**. The measure joins that visual's HTML from the hidden table **\`Design HTML\`**. The HTML is stored in chunks because model text values are limited to about 32,000 characters.
- The HTML was captured from BI Design Studio's renderer with the design's **sample values**. Images (photos, illustrations, thumbnails) are embedded in it as base64.
- Their sample-data tables and measures are still in the model. With real data, rebuild these visuals natively, or generate the HTML in DAX from your measures (for example \`"<b>" & FORMAT([Revenue], "#,0") & "</b>"\`).
- If your organisation blocks AppSource visuals, ask an admin to allow **${HTML_CONTENT_VISUAL.displayName}**. It is Microsoft-certified and makes no external calls.

| Visual | Why HTML |
| --- | --- |
${listed}
`;
}

function readme(spec: HandoffSpec, folder: string, model: SemanticModel, handoffFile: string): string {
  return `# ${spec.dashboard.name} — Power BI project

Generated by BI Design Studio on ${spec.exportedAt.slice(0, 10)}.

> **Sample data.** ${spec.sampleDataNotice}
> Replace the sample tables with real data before using the report.

## Open it

1. Extract the zip to a **short folder path**, for example \`C:\\PBI\\\`. Windows limits paths to 260 characters and the report folders are deeply nested.
2. Use **Power BI Desktop (${MIN_DESKTOP_VERSION} release or later)** on Windows.
3. Open **\`${folder}.pbip\`**. Keep the folders next to it; the report and model are stored there.
4. If visuals look empty or show a "refresh" message, select **Home → Refresh** once to load the sample tables.
5. To put it in the Power BI service, use **Home → Publish**, or **File → Save as** a .pbix in Power BI Desktop. Renaming the zip or folder to .pbix does not convert it.

## What is inside

| Item | Contents |
| --- | --- |
| \`${folder}.Report/\` | The report in Power BI's enhanced report format (PBIR): ${spec.pages.length} page(s), one folder per visual, and the dashboard theme in \`StaticResources/RegisteredResources/\`. |
| \`${folder}.SemanticModel/\` | A placeholder model in TMDL: ${model.tables.length} small import table(s) holding the sample values, with explicit measures and number formats (display folder "Sample measures"). |
| \`${handoffFile}\` | The full design handoff specification (visual mapping, positions, fields, formats). |

Each visual carries the annotation \`BIDesignStudio.componentId\`, matching \`pages[].visuals[].id\` in the handoff file.

## Connecting real data (next step)

- Each table's partition is an M \`#table(...)\` with sample rows. Replace it with a real source query, or replace the table with one from your model.
- Visuals bind to the **measures**. Rewrite each measure's DAX against real columns, keeping its name and format, and the visuals keep working.
- Category columns are sorted by a hidden "Sort Order" (tables: "Row Order") column to keep the design's order, for example months. Use a real date or sort column instead.
- Percent measures divide by 100 because the design stores percent numbers (12.5 = 12.5 %). Real ratio measures should not.
- Slicers use their own small tables and do not filter other visuals yet. Point them at real dimension fields with relationships.
- KPI change and target values are provided as extra measures (\`… Change %\`, \`… Target\`) for use in a KPI or new card visual.

${htmlSection(spec, model)}
## Known differences from the design

- Fonts: the design uses Inter; Power BI uses Segoe UI, which ships with it. Text can be slightly wider or narrower.
- Native charts use Power BI's own drawing (for example solid area fills and square bar ends). Card surfaces Power BI cannot style (gradients, backdrop photos, dot textures, glows) are pictures placed behind the transparent native visual.
- The slicer's default selection is not recreated.
- These files were generated from Microsoft's published PBIR/TMDL formats but are not produced by Power BI itself. If Power BI Desktop reports a problem, the error message names the file to check.
`;
}

/**
 * Rendering captured in the browser before building the project (see
 * `visualCapture.tsx`). Without it (e.g. in Node), every component falls back
 * to its closest native visual.
 */
export interface PbipAssets {
  /** HTML (inline styles, SVG, embedded images) for components drawn by the HTML Content visual, keyed by component id. */
  html?: ReadonlyMap<string, string>;
  /** PNG data URLs of card surfaces Power BI cannot style, keyed by component id. */
  cardBackgrounds?: ReadonlyMap<string, string>;
}

export function buildPbipProject(doc: DashboardDocument, exportedAt: string = new Date().toISOString(), assets: PbipAssets = {}): PbipProject {
  const spec = buildHandoffSpec(doc, exportedAt);
  const folder = projectFolderName(doc.name);
  const report = `${folder}.Report`;
  const semanticModel = `${folder}.SemanticModel`;
  // Only components routed to HTML use captured HTML.
  const html = new Map([...(assets.html ?? new Map<string, string>())].filter(([id]) => doc.pages.some((p) => p.components.some((c) => c.id === id && exportRoute(c).kind === 'html'))));
  const model = buildSemanticModel(doc, html);
  const tokens = resolveTheme(doc.themeId, doc.themeOverrides).tokens;
  const page = { width: spec.canvas.powerBiPage.width, height: spec.canvas.powerBiPage.height };
  const files: ProjectFiles = {};

  // Theme and images live in the report's registered resources.
  const themeFile = `BIDesignStudio-${doc.themeId.replace(/[^A-Za-z0-9_-]/g, '')}.json`;
  const resources: { name: string; path: string; type: 'CustomTheme' | 'Image' }[] = [{ name: themeFile, path: themeFile, type: 'CustomTheme' }];
  files[`${report}/StaticResources/RegisteredResources/${themeFile}`] = json(spec.theme.powerBiTheme);
  const images = new Map<string, string>();
  const addImage = (dataUrl: string, seed: string) => {
    const known = images.get(dataUrl);
    if (known) return known;
    const { bytes, ext } = decodeDataUrl(dataUrl);
    const name = `image-${pbirObjectName(seed).slice(0, 12)}.${ext}`;
    files[`${report}/StaticResources/RegisteredResources/${name}`] = bytes;
    resources.push({ name, path: name, type: 'Image' });
    images.set(dataUrl, name);
    return name;
  };

  // Pages and visuals.
  let usesHtmlVisual = false;
  const pageNames = new Set<string>();
  const pageOrder: string[] = [];
  doc.pages.forEach((p, pi) => {
    const pageName = pbirObjectName(`${doc.id}/${p.id}`, pageNames);
    pageOrder.push(pageName);
    const base = `${report}/definition/pages/${pageName}`;
    const pageBackground = doc.canvas.background ?? tokens.pageBackground;
    files[`${base}/page.json`] = json({
      $schema: PBIR_SCHEMAS.page,
      name: pageName,
      displayName: p.name,
      displayOption: 'FitToPage',
      height: page.height,
      width: page.width,
      objects: {
        background: objectEntry({ color: lit.color(pageBackground), transparency: lit.num(0) }),
        outspace: objectEntry({ color: lit.color(pageBackground), transparency: lit.num(0) }),
      },
    });
    const visualNames = new Set<string>();
    p.components.forEach((c, ci) => {
      const name = pbirObjectName(`${doc.id}/${p.id}/${c.id}`, visualNames);
      const handoff = spec.pages[pi]!.visuals[ci]!;
      const htmlMeasure = model.htmlMeasures.get(c.id);
      const route = exportRoute(c);
      const cardBackground = !htmlMeasure && route.kind === 'native' && 'cardBackground' in route ? assets.cardBackgrounds?.get(c.id) : undefined;
      const visual = buildVisualContainer({
        name,
        component: c,
        handoff,
        binding: model.bindings.get(c.id),
        tokens,
        page,
        addImage,
        ...(htmlMeasure ? { htmlMeasure } : {}),
        ...(cardBackground ? { hasCardBackground: true } : {}),
      });
      if (!visual) return;
      files[`${base}/visuals/${name}/visual.json`] = json(visual);
      if (htmlMeasure) usesHtmlVisual = true;
      if (cardBackground) {
        const bgName = pbirObjectName(`${doc.id}/${p.id}/${c.id}/card-background`, visualNames);
        const bg = buildCardBackgroundContainer({
          name: bgName,
          component: c,
          handoff,
          page,
          imageItem: addImage(cardBackground, `${c.id}-card`),
          margin: c.style.glow ? CARD_GLOW_MARGIN : 0,
        });
        files[`${base}/visuals/${bgName}/visual.json`] = json(bg);
      }
    });
  });

  files[`${report}/definition/pages/pages.json`] = json({ $schema: PBIR_SCHEMAS.pages, pageOrder, activePageName: pageOrder[0] });
  files[`${report}/definition/version.json`] = json({ $schema: PBIR_SCHEMAS.version, version: '2.0.0' });
  files[`${report}/definition/report.json`] = json({
    $schema: PBIR_SCHEMAS.report,
    themeCollection: { customTheme: { name: themeFile, reportVersionAtImport: THEME_REPORT_VERSION, type: 'RegisteredResources' } },
    // AppSource visuals are listed by name; Power BI Desktop loads them from AppSource.
    ...(usesHtmlVisual ? { publicCustomVisuals: [HTML_CONTENT_VISUAL.guid] } : {}),
    resourcePackages: [{ name: 'RegisteredResources', type: 'RegisteredResources', items: resources }],
    settings: { useStylableVisualContainerHeader: true, defaultDrillFilterOtherVisuals: true },
    annotations: [
      { name: 'BIDesignStudio.generator', value: 'BI Design Studio' },
      { name: 'BIDesignStudio.designId', value: doc.id },
      { name: 'BIDesignStudio.sampleData', value: spec.sampleDataNotice },
    ],
  });
  files[`${report}/definition.pbir`] = json({ $schema: PBIR_SCHEMAS.definitionPbir, version: '4.0', datasetReference: { byPath: { path: `../${semanticModel}` } } });

  for (const [path, content] of Object.entries(semanticModelFiles(model))) files[`${semanticModel}/${path}`] = content;

  files[`${folder}.pbip`] = json({
    $schema: PBIR_SCHEMAS.pbip,
    version: '1.0',
    artifacts: [{ report: { path: report } }],
    settings: { enableAutoRecovery: true },
  });
  const handoffFile = 'design.powerbi-handoff.json';
  files[handoffFile] = json(spec);
  files['README.md'] = readme(spec, folder, model, handoffFile);
  files['.gitignore'] = '**/.pbi/localSettings.json\n**/.pbi/cache.abf\n';

  return { folder, files, model, spec };
}
